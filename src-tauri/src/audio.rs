pub fn get_key_id(code: u32) -> &'static str {
    #[cfg(target_os = "macos")]
    {
        macos_keycode_to_dik(code)
    }
    #[cfg(target_os = "windows")]
    {
        macos_keycode_to_dik(code)
    }
    #[cfg(not(any(target_os = "macos", target_os = "windows")))]
    {
        "30" // Default to 'A'
    }
}

