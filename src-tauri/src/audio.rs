pub fn macos_keycode_to_name(code: u32) -> String {
    match code {
        49 => "Space".to_string(),
        36 => "Enter".to_string(),
        51 => "Backspace".to_string(),
        53 => "Escape".to_string(),
        _ => "Default".to_string(),
    }
}
